// agent-facing env-var auth bootstrap.
//
// Two distinct entry shapes are supported:
//
// A. **Self-managed agent (preferred, post-RFC v0.8)**
//    `SLOCK_PROFILE=<slug>` resolves a credential file at
//    `~/.slock/profiles/<slug>/credential.json` written by `slock agent login`
//    (device-code grant → `sk_agent_*` mint). The profile file carries
//    serverUrl, agentId, optional serverId, and the apiKey, so the user
//    doesn't have to re-export those by hand. The CLI flag `--profile <slug>`
//    sets this env var for convenience.
//    WIP(self-hosted-runner-layer1): this is only the credential/profile
//    entry layer. It does not implement runner lifecycle, process ownership,
//    heartbeat/status, stop/revoke orchestration, or runtime integration.
//
// B. **Daemon-injected runner / legacy machine bootstrap**
//    The daemon spawns the agent process and injects raw env vars. Two
//    sub-modes:
//      1. SLOCK_AGENT_PROXY_URL + SLOCK_AGENT_PROXY_TOKEN_FILE — daemon-local
//         proxy. The daemon keeps the canonical sk_agent_* in memory; the
//         short-lived CLI reads only a daemon-owned local proxy token.
//         SLOCK_AGENT_PROXY_TOKEN remains accepted for tests and older builds.
//      2. SLOCK_AGENT_TOKEN_FILE — legacy daemon/machine token file
//         (`sk_machine_*`), for commands not yet on /internal/agent-api/*.
//      3. SLOCK_AGENT_TOKEN — legacy token literal in the env.
//
// Mode (A) takes precedence: if SLOCK_PROFILE is set, any raw agent env
// vars from mode (B) are ignored and the override is logged to stderr. This
// matches `slock --profile <slug>` as an explicit one-shot identity switch.
//
// Required for mode (B): SLOCK_AGENT_ID, SLOCK_SERVER_URL.
// Optional: SLOCK_SERVER_ID — server resolves it from machine auth in v0;
// kept as forward-compat hook for milestone-2 agent-token mode.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

export interface AgentContext {
  agentId: string;
  serverUrl: string;
  serverId: string | null;
  token: string;
  /**
   * Wire-behavior tag: which route surface this invocation hits and where its
   * bearer comes from. This is NOT an entry-shape tag (managed vs
   * self-managed agent) — that distinction lives in `secretSource`.
   *
   *   - managed-runner      : daemon-local proxy; daemon holds sk_agent_*,
   *                           CLI carries a short-lived proxy token. Always
   *                           a daemon-spawned managed runtime.
   *   - self-hosted-runner  : CLI calls /internal/agent-api/* directly with
   *                           a real sk_agent_* loaded from a profile
   *                           credential file created by
   *                           `slock agent login`.
   *   - legacy-machine      : legacy `/internal/agent/:id/*` surface with
   *                           sk_machine_*. Pre-RFC-v0.8 daemons only.
   *
   * The literal values are pinned by Computer/Agent Runner contract §11.
   * `self-hosted-runner` is the target product model; in this PR it covers
   * layer 1 only: a profile credential generated by `slock agent login` and
   * used by the CLI to call `/internal/agent-api/*` directly. Lifecycle and
   * runtime integration are later layers of the self-hosted runner contract.
   * WIP(self-hosted-runner-layer1): do not treat this as a complete runner.
   */
  clientMode: "managed-runner" | "self-hosted-runner" | "legacy-machine";
  /**
   * Where the local secret material was loaded from. Kept separate from
   * clientMode so proxy transport does not read like a new token principal.
   */
  secretSource:
    | "agent-proxy-token-file"
    | "agent-proxy-token-env"
    | "profile-credential-file"
    | "legacy-token-file"
    | "legacy-token-env";
  activeCapabilities: string[] | null;
  /**
   * For profile-credential mode: where on disk the credential file lives.
   * Useful for `whoami` / debugging without leaking the bearer.
   */
  profileSlug?: string;
  profileCredentialPath?: string;
}

interface ProfileCredentialFile {
  schemaVersion?: number;
  serverUrl: string;
  agentId: string;
  agentName?: string;
  serverId?: string | null;
  credentialId?: string;
  scopes?: string[];
  apiKey: string;
  createdAt?: string;
}

const RAW_AGENT_ENV_KEYS = [
  "SLOCK_AGENT_ID",
  "SLOCK_SERVER_URL",
  "SLOCK_SERVER_ID",
  "SLOCK_AGENT_PROXY_URL",
  "SLOCK_AGENT_PROXY_TOKEN",
  "SLOCK_AGENT_PROXY_TOKEN_FILE",
  "SLOCK_AGENT_TOKEN_FILE",
  "SLOCK_AGENT_TOKEN",
] as const;

export class AgentBootstrapError extends Error {
  constructor(public readonly code: string, message: string) {
    super(message);
    this.name = "AgentBootstrapError";
  }
}

/**
 * Effective profile-credential root, in precedence order:
 *
 *   1. `SLOCK_PROFILE_DIR` — explicit override of the per-profile directory
 *      (the test/fixture/operator escape hatch; targets a single profile).
 *   2. `SLOCK_HOME/profiles/<slug>` — the daemon-owned app-level user-data
 *      root. Honors the §10 SLOCK_HOME state-isolation invariant
 *      (Dayu #wg-slock-computer msg=15528a10): all user-visible state
 *      reads/writes scope to the effective SLOCK_HOME; the default
 *      `~/.slock/...` path is only legitimate when SLOCK_HOME is unset.
 *      `packages/cli/AGENTS.md` already pins this for daemon-owned local
 *      state — profile credentials are exactly that.
 *   3. `$HOME/.slock/profiles/<slug>` — fallback for un-managed shells
 *      where neither SLOCK_HOME nor SLOCK_PROFILE_DIR is exported.
 *
 * `login.ts` MUST resolve via the same function so a write at login time
 * lands at the same path a subsequent `--profile <slug>` read uses.
 */
export function resolveProfileDir(slug: string, env: NodeJS.ProcessEnv = process.env): string {
  if (env.SLOCK_PROFILE_DIR) {
    return env.SLOCK_PROFILE_DIR;
  }
  if (env.SLOCK_HOME) {
    return path.join(env.SLOCK_HOME, "profiles", slug);
  }
  const home = env.HOME ?? os.homedir();
  return path.join(home, ".slock", "profiles", slug);
}

function resolveProfileCredentialPath(slug: string, env: NodeJS.ProcessEnv): string {
  return path.join(resolveProfileDir(slug, env), "credential.json");
}

function readProfileCredential(slug: string, env: NodeJS.ProcessEnv): {
  filePath: string;
  data: ProfileCredentialFile;
} {
  const filePath = resolveProfileCredentialPath(slug, env);
  let raw: string;
  try {
    raw = fs.readFileSync(filePath, "utf-8");
  } catch (err) {
    throw new AgentBootstrapError(
      "PROFILE_FILE_UNREADABLE",
      `SLOCK_PROFILE=${slug} resolved to ${filePath}, which could not be read: ${(err as Error).message}. Run \`slock agent login\` to mint a credential.`,
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new AgentBootstrapError(
      "PROFILE_FILE_INVALID",
      `${filePath} is not valid JSON: ${(err as Error).message}`,
    );
  }
  if (
    !parsed
    || typeof parsed !== "object"
    || typeof (parsed as ProfileCredentialFile).apiKey !== "string"
    || typeof (parsed as ProfileCredentialFile).agentId !== "string"
    || typeof (parsed as ProfileCredentialFile).serverUrl !== "string"
  ) {
    throw new AgentBootstrapError(
      "PROFILE_FILE_INVALID",
      `${filePath} is missing required fields (apiKey, agentId, serverUrl).`,
    );
  }
  return { filePath, data: parsed as ProfileCredentialFile };
}

function readTokenFromFile(filePath: string): string {
  let raw: string;
  try {
    raw = fs.readFileSync(filePath, "utf-8");
  } catch (err) {
    throw new AgentBootstrapError(
      "TOKEN_FILE_UNREADABLE",
      `SLOCK_AGENT_TOKEN_FILE=${filePath} could not be read: ${(err as Error).message}`,
    );
  }
  const token = raw.trim();
  if (!token) {
    throw new AgentBootstrapError(
      "TOKEN_FILE_EMPTY",
      `SLOCK_AGENT_TOKEN_FILE=${filePath} is empty`,
    );
  }
  return token;
}

export function loadAgentContext(env: NodeJS.ProcessEnv = process.env): AgentContext {
  const activeCapabilities = env.SLOCK_AGENT_ACTIVE_CAPABILITIES
    ? env.SLOCK_AGENT_ACTIVE_CAPABILITIES.split(",").map((cap) => cap.trim()).filter(Boolean)
    : null;

  // (A) Self-managed agent: profile credential file is the single source of
  // truth for serverUrl/agentId/apiKey. Profile wins over any raw agent env
  // vars that happen to be set (typical case: user runs `slock --profile X`
  // inside a daemon-spawned shell that already exports SLOCK_AGENT_*). We log
  // the override to stderr so the identity switch is visible — silent
  // shadowing here would make "why am I posting as the wrong agent?" a
  // nightmare to debug.
  const profileSlug = env.SLOCK_PROFILE;
  if (profileSlug) {
    const shadowed = RAW_AGENT_ENV_KEYS.filter((k) => env[k]);
    if (shadowed.length > 0) {
      process.stderr.write(
        `slock: SLOCK_PROFILE=${profileSlug} active; ignoring ${shadowed.join(", ")} from env.\n`,
      );
    }
    const { filePath, data } = readProfileCredential(profileSlug, env);
    return {
      agentId: data.agentId,
      serverUrl: data.serverUrl,
      serverId: data.serverId ?? null,
      token: data.apiKey,
      clientMode: "self-hosted-runner",
      secretSource: "profile-credential-file",
      activeCapabilities,
      profileSlug,
      profileCredentialPath: filePath,
    };
  }

  // (B) Daemon-injected / legacy machine bootstrap.
  const agentId = env.SLOCK_AGENT_ID;
  const serverUrl = env.SLOCK_SERVER_URL;
  const serverId = env.SLOCK_SERVER_ID ?? null;

  if (!agentId) throw new AgentBootstrapError("MISSING_AGENT_ID", "SLOCK_AGENT_ID is required");
  if (!serverUrl) throw new AgentBootstrapError("MISSING_SERVER_URL", "SLOCK_SERVER_URL is required");

  const agentProxyUrl = env.SLOCK_AGENT_PROXY_URL;
  const agentProxyToken = env.SLOCK_AGENT_PROXY_TOKEN;
  const agentProxyTokenFile = env.SLOCK_AGENT_PROXY_TOKEN_FILE;
  if (agentProxyUrl || agentProxyToken || agentProxyTokenFile) {
    if (!agentProxyUrl) {
      throw new AgentBootstrapError("MISSING_AGENT_PROXY_URL", "SLOCK_AGENT_PROXY_URL is required when agent proxy auth is set");
    }
    if (agentProxyToken && agentProxyTokenFile) {
      throw new AgentBootstrapError(
        "MULTIPLE_AGENT_PROXY_TOKENS",
        "Set only one of SLOCK_AGENT_PROXY_TOKEN or SLOCK_AGENT_PROXY_TOKEN_FILE",
      );
    }
    const token = agentProxyToken ?? (agentProxyTokenFile ? readTokenFromFile(agentProxyTokenFile) : null);
    if (!token) {
      throw new AgentBootstrapError(
        "MISSING_AGENT_PROXY_TOKEN",
        "SLOCK_AGENT_PROXY_TOKEN_FILE or SLOCK_AGENT_PROXY_TOKEN is required when SLOCK_AGENT_PROXY_URL is set",
      );
    }
    return {
      agentId,
      serverUrl: agentProxyUrl,
      serverId,
      token,
      clientMode: "managed-runner",
      secretSource: agentProxyTokenFile ? "agent-proxy-token-file" : "agent-proxy-token-env",
      activeCapabilities,
    };
  }

  const tokenFile = env.SLOCK_AGENT_TOKEN_FILE;
  if (tokenFile) {
    return {
      agentId,
      serverUrl,
      serverId,
      token: readTokenFromFile(tokenFile),
      clientMode: "legacy-machine",
      secretSource: "legacy-token-file",
      activeCapabilities,
    };
  }

  const tokenLiteral = env.SLOCK_AGENT_TOKEN;
  if (tokenLiteral) {
    return {
      agentId,
      serverUrl,
      serverId,
      token: tokenLiteral,
      clientMode: "legacy-machine",
      secretSource: "legacy-token-env",
      activeCapabilities,
    };
  }

  throw new AgentBootstrapError(
    "MISSING_TOKEN",
    "Neither SLOCK_AGENT_PROXY_TOKEN_FILE, SLOCK_AGENT_PROXY_TOKEN, SLOCK_AGENT_TOKEN_FILE nor SLOCK_AGENT_TOKEN is set. The daemon should inject one of these when spawning the agent process.",
  );
}
