#!/usr/bin/env node
// Generates src/components/brand-illustration/brand-illustration-art.ts from
// the brand illustrations in design/assets/Illustrations.
//
//   node scripts/build-illustrations.mjs           write the module
//   node scripts/build-illustrations.mjs --check   exit 1 if it is stale
//
// Each SVG there is one drawing on its own grid (one cell = one viewBox unit),
// in two colours: paper (#FFFAEF) for the cells the ink encloses, then ink
// (#141111). The module keeps the grid's size and each colour's path; the
// component draws them in tokens, not in these colours.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const assetsDir = path.join(packageDir, "../../design/assets/Illustrations");
const modulePath = path.join(
  packageDir,
  "src/components/brand-illustration/brand-illustration-art.ts",
);

function art(name) {
  const svg = readFileSync(path.join(assetsDir, `${name}.svg`), "utf8");
  const box = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!box) throw new Error(`design/assets/Illustrations/${name}.svg has no integer viewBox`);
  const paths = Object.fromEntries(
    [...svg.matchAll(/<path fill="([^"]+)" d="([^"]+)"\/>/g)].map(([, fill, d]) => [
      fill.toUpperCase(),
      d,
    ]),
  );
  if (!paths["#141111"]) throw new Error(`design/assets/Illustrations/${name}.svg has no ink path`);
  return {
    width: Number(box[1]),
    height: Number(box[2]),
    ink: paths["#141111"],
    paper: paths["#FFFAEF"] ?? "",
  };
}

export function renderModule() {
  const names = readdirSync(assetsDir)
    .filter((file) => file.endsWith(".svg"))
    .map((file) => file.slice(0, -4))
    .sort();
  const key = (name) => (/^[a-z]+$/.test(name) ? name : `"${name}"`);
  const entries = names.map((name) => {
    const { width, height, ink, paper } = art(name);
    return `  ${key(name)}: {\n    width: ${width},\n    height: ${height},\n    paper: "${paper}",\n    ink: "${ink}",\n  },`;
  });
  return `// Generated from design/assets/Illustrations by scripts/build-illustrations.mjs.
// Do not edit this file; edit the SVGs and run
// \`vp run @botiverse/raft-ui#build:illustrations\`.
export const BRAND_ILLUSTRATION_ART = {
${entries.join("\n")}
} as const;
`;
}

function main(argv) {
  const source = renderModule();
  if (argv.includes("--check")) {
    if (readFileSync(modulePath, "utf8") !== source) {
      console.error(
        "brand-illustration-art.ts is out of date with design/assets/Illustrations. Run `vp run @botiverse/raft-ui#build:illustrations`.",
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(modulePath, source);
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2));
